#!/usr/bin/env python3
"""
NovexOS - tools/gen_font.py
Rasterises JetBrains Mono (SIL OFL 1.1) into an 8x16 anti-aliased glyph atlas
covering Windows-1252 (English + French: é è ê ë à â ä ç î ï ô ö ù û ü ÿ œ æ
É È À Ç Œ Æ « » € ’ …).  Output: src/font_aa.c

Usage:  python3 tools/gen_font.py [Regular.ttf Bold.ttf]
        (without arguments the fonts are downloaded from GitHub)
Needs:  pip install pillow
"""
import os, sys, urllib.request
from PIL import Image, ImageDraw, ImageFont

BASE = "https://raw.githubusercontent.com/JetBrains/JetBrainsMono/master/fonts/ttf/"
SIZE, BASELINE, XOFF, GAMMA = 12, 13, 0.4, 0.78
CW, CH = 8, 16

def fetch(name):
    path = os.path.join("/tmp", name)
    if not os.path.exists(path):
        urllib.request.urlretrieve(BASE + name, path)
    return path

def cp1252_char(b):
    if b == 0x7F: return None
    try:
        return bytes([b]).decode("cp1252")
    except UnicodeDecodeError:
        return None

def render(font, ch):
    img = Image.new("L", (CW, CH), 0)
    if ch is not None and ch != " ":
        ImageDraw.Draw(img).text((XOFF, BASELINE), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    out = []
    for y in range(CH):
        for x in range(CW):
            a = px[x, y] / 255.0
            out.append(round(255 * (a ** GAMMA)))
    return out

def table(path):
    font = ImageFont.truetype(path, SIZE)
    rows = []
    for b in range(0x20, 0x100):
        ch = cp1252_char(b)
        if b == 0xA0: ch = None          # no-break space
        rows.append(render(font, ch))
    return rows

def emit(name, rows):
    s = "static const uint8_t %s[224][%d] = {\n" % (name, CW * CH)
    for i, r in enumerate(rows):
        s += "    /* 0x%02X */ {" % (0x20 + i)
        s += ",".join(str(v) for v in r) + "},\n"
    return s + "};\n\n"

def main():
    reg = sys.argv[1] if len(sys.argv) > 2 else fetch("JetBrainsMono-Regular.ttf")
    bold = sys.argv[2] if len(sys.argv) > 2 else fetch("JetBrainsMono-Bold.ttf")
    out = ('/*\n * NovexOS - font_aa.c  (GENERATED by tools/gen_font.py - do not edit)\n'
           ' * JetBrains Mono, SIL Open Font License 1.1 (see assets/fonts/OFL-JetBrainsMono.txt)\n'
           ' * 8x16 cells, 8-bit coverage, Windows-1252 bytes 0x20..0xFF.\n */\n\n'
           '#include "font_aa.h"\n\n')
    out += emit("aa_regular", table(reg))
    out += emit("aa_bold", table(bold))
    out += ('const uint8_t *font_aa_glyph(uint8_t c, int bold) {\n'
            '  if (c < 0x20) c = 0x20;\n'
            '  return bold ? aa_bold[c - 0x20] : aa_regular[c - 0x20];\n}\n')
    dst = os.path.join(os.path.dirname(__file__), "..", "src", "font_aa.c")
    open(dst, "w").write(out)
    print("wrote", os.path.normpath(dst), len(out), "bytes of source")

main()
